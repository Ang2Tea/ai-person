/// Фоновая задача, запускаемая один раз при старте бинарника (nightly-
/// консолидация, извлечение по простою, проактивные сообщения) — общий
/// интерфейс, чтобы сборка (`app`) держала их списком, не перечисляя
/// каждую по имени.
pub trait BackgroundJob: Send + 'static {
    fn spawn(self: Box<Self>);
}

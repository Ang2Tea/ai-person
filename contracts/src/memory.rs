/// Память личности бота — commitments (краткосрочная память задач/обещаний),
/// долгосрочный дневник фактов и "ночные" insights. В отличие от
/// `ChannelHistory` это не компенсация ограничений конкретного канала связи
/// (даже у ботов с полным доступом к истории есть свой аналог краткосрочной
/// памяти), а самостоятельная часть бота — прячется за трейт не ради канала,
/// а чтобы `bot-core` не был жёстко завязан на конкретный `Storage`-backend.
/// Используется только как `M: Memory` generic-параметр, не `dyn` (в рамках
/// одного запуска реализация не подменяется), поэтому методы возвращают
/// `impl Future` напрямую — как у `Storage`/`Llm`, без ручного boxing.
pub trait Memory: Send + Sync {
    /// System prompt личности — статическая часть плюс актуальные insights
    /// (обновляются ночной консолидацией и подхватываются без перезапуска,
    /// поэтому не может быть просто полем `&str`). Данные памяти/личности,
    /// не логики бота, поэтому не хранится на `ChatBot` отдельно.
    fn system_prompt(&self) -> impl Future<Output = String> + Send;

    /// Сколько последних сообщений истории канала стоит оставлять после
    /// извлечения фактов (`extract`) — используется и вызывающим (после
    /// `extract`, чтобы обрезать `ChannelHistory`), и воркером извлечения по
    /// простою (чтобы решить, есть ли вообще что извлекать сверх этого
    /// количества).
    fn keep_last_messages(&self) -> usize;

    /// Commitments + автоматический RAG-поиск релевантных фактов долгосрочной
    /// памяти по тексту запроса.
    fn recall(
        &self,
        chat_id: i64,
        user_id: i64,
        query: &str,
    ) -> impl Future<Output = Option<String>> + Send;

    /// Открытые задачи/обещания — одним общим списком на всю личность, не по
    /// чату (обещание из одного разговора должно быть видно и в другом).
    /// Нужны и без `query` (см. проактивный ход, там `recall` не вызывается
    /// вовсе, но commitments в system prompt всё равно должны попасть).
    fn commitments(&self) -> impl Future<Output = Option<String>> + Send;

    /// Извлечь факты и обновить commitments по итогам хода — принимает уже
    /// готовый транскрипт (вызывающий достаёт его через `ChannelHistory`,
    /// `Memory` о нём ничего не знает).
    fn extract(&self, chat_id: i64, transcript: &str) -> impl Future<Output = ()> + Send;

    /// Явное "запомни прямо сейчас" (инструмент `remember`) — прямое
    /// сохранение факта, без прохода через LLM-извлечение, в отличие от
    /// `extract`. Возвращает `false`, если факт отброшен как дубликат уже
    /// существующего похожего факта того же чата.
    fn remember(
        &self,
        chat_id: i64,
        text: &str,
        confidence: f32,
        visibility_public: bool,
        about_users: &[i64],
    ) -> impl Future<Output = bool> + Send;

    /// Один прогон ночной консолидации (слияние похожих фактов, удаление
    /// нерелевантных/устаревших, пересборка insights).
    fn consolidate(&self) -> impl Future<Output = Result<(), String>> + Send;
}
